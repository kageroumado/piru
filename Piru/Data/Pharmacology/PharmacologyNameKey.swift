/// The one substance-name folding + lookup mechanism for the pharmacology tables
/// (`SubstanceModelDatabase`, `MechanismOfActionDatabase`, `MetabolicModulation`), and the shared
/// alias relation most of them key on.
///
/// A table that needs a *different* relation keeps its own. Never merge them: they encode different
/// questions. To ``sharedAliases`` `lisdexamfetamine` is its own name; to
/// `SubstanceModelDatabase` it aliases to `amphetamine`, because there it must inherit amphetamine's
/// PD scalars. One shared table would force one relation onto the other. `MetabolicModulation`'s
/// lives in the database, in `pharmacology_matchers` under its own `relation` value, for the same
/// reason.
nonisolated enum PharmacologyNameKey {
    /// The one fold: lowercased, whitespace/newline-trimmed.
    static func fold(_ name: String) -> String {
        name.lowercased().trimmingCharacters(in: .whitespacesAndNewlines)
    }

    /// Direct hit first, then one alias hop. Direct-first means adding an
    /// alias row can only turn a miss into a hit: a spelling that is itself a
    /// data key always resolves to its own value, even when an alias row also
    /// claims it.
    static func resolve<Value>(
        _ name: String,
        in data: [String: Value],
        aliases: [String: String],
    ) -> Value? {
        let key = fold(name)
        if let direct = data[key] { return direct }
        if let canonical = aliases[key] { return data[canonical] }
        return nil
    }

    /// The canonical key alone (alias target when one exists, else the fold),
    /// for callers that match against a set or group rather than look up a
    /// value.
    static func canonical(_ name: String, aliases: [String: String]) -> String {
        let key = fold(name)
        return aliases[key] ?? key
    }

